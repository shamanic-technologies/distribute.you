import fs from "node:fs"; import path from "node:path"; import { createRequire } from "node:module";
// Run from anywhere: node apps/dashboard/scripts/gen-duotone-icons.mjs
const app = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const require = createRequire(app + "/package.json");
const React = require("react");
const dist = path.dirname(require.resolve("@phosphor-icons/react/dist/csr/Acorn.es.js")).replace(/\/csr$/, "");
const files = ["src/components/v2/catalogue-mark.tsx", "src/components/v2/catalogue-mark-icons.tsx"];
const names = new Set();
for (const f of files) {
  const src = fs.readFileSync(path.join(app, f), "utf8");
  const block = src.match(/import \{\n([\s\S]*?)\} from "@\/components\/v2\/duotone-icons";/);
  if (!block) throw new Error("no duotone import in " + f);
  for (const m of block[1].matchAll(/^\s+(\w+)Icon,$/gm)) names.add(m[1]);
}
const out = [];
const toNode = (el) => {
  if (typeof el !== "object" || !el) throw new Error("bad child " + el);
  const { children, ...props } = el.props;
  if (children !== undefined) throw new Error("nested children in " + el.type);
  return [el.type, props];
};
for (const n of [...names].sort()) {
  const mod = await import(path.join(dist, "defs", n + ".es.js"));
  const weights = mod.default;
  const frag = weights.get("duotone");
  if (frag.type !== React.Fragment) throw new Error("not fragment " + n);
  const kids = React.Children.toArray(frag.props.children).map((k) => { const { key, ...rest } = k; return k; });
  const nodes = [].concat(frag.props.children).map(toNode);
  out.push(`export const ${n}Icon = duotone("${n}Icon", ${JSON.stringify(nodes)});`);
}
const header = `"use client";

// GENERATED by scripts/gen-duotone-icons.mjs from @phosphor-icons/react's own defs: DO NOT EDIT BY HAND.
//
// The catalogue marks draw Phosphor icons in ONE weight (duotone), but each Phosphor icon module
// carries all six weights' SVG paths: ${names.size} icons in the v2 shell were ~1 MB of JavaScript on
// every v2 page (MON-PAGE-SPEED-FLOOR-1120). These are the same paths, duotone only, drawn by
// \`duotone()\` exactly as Phosphor's IconBase draws them (same svg attributes, same children).
// Adding a served name: add its \`XxxIcon\` here to the import block of catalogue-mark(-icons).tsx, then re-run the generator.
import { forwardRef } from "react";
import type { Icon, IconProps } from "@phosphor-icons/react";

type SvgNode = [string, Record<string, string>];

function duotone(displayName: string, nodes: SvgNode[]): Icon {
  const C = forwardRef<SVGSVGElement, IconProps>(function DuotoneIcon(
    { alt, color = "currentColor", size = "1em", weight: _weight, mirrored = false, children, ...rest },
    ref,
  ) {
    return (
      <svg
        ref={ref}
        xmlns="http://www.w3.org/2000/svg"
        width={size}
        height={size}
        fill={color}
        viewBox="0 0 256 256"
        transform={mirrored ? "scale(-1, 1)" : undefined}
        {...rest}
      >
        {!!alt && <title>{alt}</title>}
        {children}
        {nodes.map(([T, props], i) => {
          const El = T as "path";
          return <El key={i} {...props} />;
        })}
      </svg>
    );
  });
  C.displayName = displayName;
  return C as Icon;
}
`;
fs.writeFileSync(path.join(app, "src/components/v2/duotone-icons.tsx"), header + "\n" + out.join("\n") + "\n");
console.log(names.size, "icons");
